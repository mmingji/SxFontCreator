// 「单页试打」那一页写什么（零依赖纯数据）
//
// 由来（2026-10-16 用户口径：**提高观感**）：原来试打页排的是"频序前 136 字"—— 一页互不相干的常用字，
//   写起来像抄字帖、也没有成品感。改成**一篇短文**：写一遍既能确认版式与打印设置，又像写了一页作品；
//   而且这些字会直接进字体，试打出来的字体立刻能打出一句完整的话。
// 选文标准（三条，缺一不可）：
//   ① **每个字与标点都在字表 8274 内**（硬约束：印在 PDF 上的字符必须在表内，否则印成方块，决策 一-4 (a)）；
//   ② **一页放得下**（≤ 136 格 —— 超一页就与"单页试打"这个名字不符了）；
//   ③ **尽量用常用字**（落在频序前面，试打出的字形更"能用"）且**读起来有味道**（这是本次改动的出发点）。
// 现选：《岳阳楼记》名句段（范仲淹）= **标题 9 字 + 正文 68 字符 = 77 字符**，一页 136 格内。
//   正文汉字 **83% 落在频序前 1000**、且**没有一个字频序在 2000 之后**（同一批候选里数据最好的那一档）。
// **标题就在第一行、与正文连排**（2026-10-16 用户口径："标题单独作为内容印在主区第一行"）：
//   标题占第一行的前 9 格，正文从第 10 格接着排 —— 也就是说第一行是"《岳阳楼记》节选不以物喜，不以己悲。居"。
//   **为什么不让标题独占一行（后面补空格）**：空格**不在字表 8274 内**（基础字符 169 = 95 个**可打印** ASCII
//   + 30 中文标点 + 44 全角符号，收字时就排除了空白），补空格会往纸面塞表外字符 —— 按硬约束 ① 不行。
//   **另外**：正因为字表不含空白，**四个档位（试打 / 常用 6500 / 全量 / 自定义）的模板都不会产生空白字符**，
//   识别端不会遇到"这一格该是什么字却拿到空格"的情形（用户 2026-10-16 专门确认过这件事）。
// 与「字体预览」的关系：第 3 步「随机一句话」随机的就是**正文里的句子**（不含标题）。

/** 这一页的标题（写在第 1 行开头，用户会照着写下来） */
export const SINGLE_PAGE_TITLE = '《岳阳楼记》节选'

/** 正文（不含标题；含标点）—— 「随机一句话」从这个范围里取句 */
export const SINGLE_PAGE_BODY =
  '不以物喜，不以己悲。居庙堂之高则忧其民，处江湖之远则忧其君。是进亦忧，退亦忧。然则何时而乐耶？其必曰：先天下之忧而忧，后天下之乐而乐乎！'

/** 印在模板上的完整内容：标题 + 正文（连排，见文件头；**不含任何空白字符**） */
export const SINGLE_PAGE_TEXT = SINGLE_PAGE_TITLE + SINGLE_PAGE_BODY

/** 这段文字的出处（只用于注释与文档，**不上界面** —— 界面里不出现书名章节这类描述，通用约定） */
export const SINGLE_PAGE_SOURCE = '《岳阳楼记》名句段（范仲淹）'

/**
 * 按**句末标点**切句（。？！保留在句尾）：给第 3 步「随机一句话」当句库用。
 * 为什么按句末切而不是按逗号切：逗号切出来是半句（"不以物喜"），读着别扭；按句末切每一句都完整。
 */
export function splitSentences(text) {
  const out = []
  let buf = ''
  for (const ch of String(text || '')) {
    buf += ch
    if (ch === '。' || ch === '？' || ch === '！') {
      out.push(buf)
      buf = ''
    }
  }
  if (buf) out.push(buf)
  return out
}

/** **正文**里的句子（模块级算一次；5 句）—— 不含标题（标题不是"一句话"） */
export const SINGLE_PAGE_SENTENCES = splitSentences(SINGLE_PAGE_BODY)

/**
 * 随机取一句（第 3 步「随机一句话」用）。
 * 传入上一句时**避开它**（点一下还是同一句，用户会以为按钮坏了）；只有一句时原样返回。
 * @param {string} [current] 当前这一句
 * @returns {string}
 */
export function pickSinglePageSentence(current) {
  const list = SINGLE_PAGE_SENTENCES
  if (list.length <= 1) return list[0] || ''
  const rest = list.filter((s) => s !== current)
  return rest[Math.floor(Math.random() * rest.length)]
}

/** 这一页要写的字数（按**码点**算：字表里有扩展 B 区汉字，用 .length 会多算）—— 界面文案与档位说明用它 */
export function singlePageCharCount() {
  return Array.from(SINGLE_PAGE_TEXT).length
}
