// 「单页试打」那一页写什么（零依赖纯数据）
//
// 由来（2026-10-16 用户口径：**提高观感**）：最早试打页排的是"频序前 136 字"—— 一页互不相干的
//   常用字，写起来像抄字帖、也没有成品感。
// **2026-10-18 改判（用户口径，本文件的现口径）**：改成**一页名句集锦**，三条约束缺一不可 ——
//   ① **汉字一个都不重复**（用户 2026-10-18 的硬要求："保证我们产出的所有模板都不会有重复的字"：
//      重复字在成字时只有一份能进字体，白占格子；字表本身无重复、各档位都是字表切片，所以试打页
//      曾是**唯一**会重复的模板，这一版把它也去掉）；
//   ② **每个字与标点都在字表 8274 内**（决策 一-4 (a)：表外字符会印成方块）；
//   ③ **一页放得下**（≤ 136 格）且**字尽量常用**（现选这 9 句：汉字 104 个字字不同、全部落在频序
//      前 3000 内 —— 上一版《岳阳楼记》节选 77 字符里只有 50 个不同的字，另有一版《千字文》虽然
//      天然不重复，但含"昃（频序 6091）""柰（6180）"这类生僻字，被用户否掉）。
// **标点统一排在最后**（用户口径）：句间的逗号句号不插在汉字中间 —— 汉字按句子顺序连排成一片，
//   标点**去重后**按首次出现的顺序排在这一页的末尾（所以这里只有「，。」两个）。
//   为什么要去重：只要出现两次同样的标点，就违背了"整页不重复"这条（标点也是字符、也占格、也成字形）。
// **与「随机一句话」的关系**：第 3 步字体预览的「随机一句话」取的是这 9 句原句（带标点，见
//   lib/fontPreview.js）—— 预览里出现的字就是用户刚写的那一页上的。
// **不强制铺满 136 格**（用户明确）：104 个汉字 + 2 个标点 = 106 格，后面留空即可。

/** 这一页印的名句原句（带标点；「随机一句话」的句库就是它）
 *  **顺序是人工排的**（2026-10-18 用户同意后调）：由景入情、由情入志 —— 山居 → 塞外 → 春夜 → 行旅
 *  → 知己 → 境遇 → 晚节 → 志向 → 壮怀；每句都是完整句子，读下来是一条线，不是随机拼在一起。
 *  换顺序不影响任何约束（汉字集合不变、仍然一个不重复；标点排序也不变）。 */
const SINGLE_PAGE_LINES = [
  '明月松间照，清泉石上流。',
  '大漠孤烟直，长河落日圆。',
  '随风潜入夜，润物细无声。',
  '借问酒家何处有，牧童遥指杏花村。',
  '海内存知己，天涯若比邻。',
  '沉舟侧畔千帆过，病树前头万木春。',
  '老当益壮，宁移白首之心。',
  '不畏浮云遮望眼，只缘身在最高层。',
  '醉里挑灯看剑，梦回吹角连营。'
]

/** 汉字与标点的分界（标点 = 非汉字、非空白；与字表口径一致） */
const isHan = (ch) => /[\u4e00-\u9fff\u3400-\u4dbf\uf900-\ufaff]/.test(ch)

/** 印在纸上的**汉字部分**：按句子顺序连排，一个不重复 */
export const SINGLE_PAGE_HANZI = SINGLE_PAGE_LINES.map((line) => Array.from(line).filter(isHan).join('')).join('')

/** 印在纸上的**标点部分**：去重、按首次出现的顺序（这样整页仍然一个字都不重复） */
export const SINGLE_PAGE_PUNCTS = (() => {
  const seen = []
  for (const line of SINGLE_PAGE_LINES) {
    for (const ch of Array.from(line)) {
      if (!isHan(ch) && !/\s/.test(ch) && !seen.includes(ch)) seen.push(ch)
    }
  }
  return seen
})()

/** 印在模板上的完整内容：汉字连排 + 标点排在最后（**不含任何空白字符**，空格不在字表内） */
export const SINGLE_PAGE_TEXT = SINGLE_PAGE_HANZI + SINGLE_PAGE_PUNCTS.join('')

/** 「随机一句话」的句库（= 这 9 句原句；句库必须是原句，否则预览里就没有标点了） */
export const SINGLE_PAGE_SENTENCES = SINGLE_PAGE_LINES.slice()

/**
 * 随机取一句（第 3 步「随机一句话」用）。
 * 传入上一句时**避开它**（点一下还是同一句，用户会以为按钮坏了）；只有一句时原样返回。
 * @param {string} [current] 当前这一句
 * @returns {string}
 */
export function pickSinglePageSentence(current) {
  const list = SINGLE_PAGE_SENTENCES
  if (list.length <= 1) return list[0] || ''
  const rest = list.filter((s) => s !== current)
  return rest[Math.floor(Math.random() * rest.length)]
}

/** 这一页要写的字数（按**码点**算：字表里有扩展区汉字，用 .length 会多算）—— 界面文案与档位说明用它 */
export function singlePageCharCount() {
  return Array.from(SINGLE_PAGE_TEXT).length
}
